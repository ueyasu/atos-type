export const WORDS: Record<WordTier, string[]> = {
  easy: EASY_WORDS,
  normal: NORMAL_WORDS,
  hard: HARD_WORDS,
  expert: EXPERT_WORDS,
};

/**
 * 単語を重複なく順不同で取り出す「袋」を作る。
 * 袋が空になったら自動で補充する。
 */
export function createWordBag(tier: WordTier): () => string {
  let bag: string[] = [];
  return () => {
    if (bag.length === 0) {
      bag = [...WORDS[tier]];
      // Fisher-Yates シャッフル
      for (let i = bag.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [bag[i], bag[j]] = [bag[j], bag[i]];
      }
    }
    return bag.pop()!;
  };
}
